#include <string.h>

int	ft_strcmp(char *s1, char *s2)
{
	int	collect;

	while (*s1 != '\0' && *s2 != '\0' && *s1 == *s2)
	{
		s1++;
		s2++;
	}
	if (*s1 == *s2)
	{
		collect = 0;
	}
	else
	{
		collect = *s1 - *s2;
	}
	return (collect);
}
